def pick_word(
    rng: random.Random | None = None,
    *,
    used: set[str] | None = None,
) -> str:
    """Return a random word from WORDS, preferring ones not in *used*."""
    source = rng or random
    pool = [w for w in WORDS if used is None or w not in used]
    if not pool:
        pool = list(WORDS)
    return source.choice(pool)
